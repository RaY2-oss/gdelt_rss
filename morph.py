# -*- coding: utf-8 -*-
"""morph.py — постановка подставленного термина в нужный падеж.

Проблема. Словарь подставляет именительный падеж, а стоять он может где
угодно: "в Анкара" вместо "в Анкаре", "из Ташкент" вместо "из Ташкента".
Это ошибка, которую вносим МЫ САМИ, и её обязано не быть.

Решение. В русском падеж существительного после предлога задаётся самим
предлогом: "из" всегда требует родительного, "к" — дательного, "в"+статика —
предложного. Значит, достаточно посмотреть на слово ПЕРЕД точкой подстановки,
определить падеж по предлогу и поставить термин в него через pymorphy3.

Где остаётся неоднозначность. Предлоги в/на/за/под/с управляют двумя падежами:
"в Анкаре" (где) против "в Анкару" (куда). Различить можно только по глаголу,
а он бывает далеко или отсутствует вовсе. Для новостных текстов о местах
статическое значение сильно преобладает, поэтому по умолчанию берём его;
переопределяется через PREP_DEFAULT.

Чего этот модуль НЕ делает. Он не чинит согласование, которое сломала сама
модель перевода ("Полицейский зарезал" вместо "заколот"). Это уже качество
выхода NMT, лечится отдельным слоем — см. README и translate_worker.
"""
import logging
import re

log = logging.getLogger("gdelt_rss")

_morph = None


def _analyzer():
    global _morph
    if _morph is None:
        import pymorphy3
        _morph = pymorphy3.MorphAnalyzer()
    return _morph


# Предлог -> падеж. Для двухпадежных берём преобладающее в новостях значение.
PREP_CASE = {}
for _preps, _case in (
    ("из из-за из-под от до у для без около возле вблизи вокруг кроме против "
     "среди после ради вместо насчёт касательно относительно позади внутри "
     "напротив мимо сверх выше ниже", "gent"),
    ("к ко по благодаря вопреки согласно навстречу", "datv"),
    ("через про сквозь спустя включая", "accs"),
    ("с со над под перед пред между рядом", "ablt"),
    # "по" — дательный ("данные по области", "поездка по стране"); предложное
    # значение ("по прибытии") в новостях редкость и им жертвуем.
    ("в во на о об обо при", "loct"),
):
    for _p in _preps.split():
        PREP_CASE[_p] = _case

_WORD = re.compile(r"[А-Яа-яЁёA-Za-z-]+")

# в/на управляют двумя падежами: "в Анкаре" (где) и "в Анкару" (куда).
# Различает это глагол или отглагольное существительное движения. Список
# по основам, чтобы ловить все формы: приехал/приехала/приезжает/приезд.
_MOTION = re.compile(
    r"(приезж|приех|прибы|прибу|отправ|поех|поед|направ|вылет|прилет|улет|"
    r"верну|возвращ|переех|переезж|въех|въезж|вошл|войд|привез|привёз|привоз|"
    r"доставл|достав|экспорт|импорт|визит|поездк|поставк|командиров|переброс|"
    r"вступил|вступ|инвестир|вложил|прибытие|приезд|въезд)", re.IGNORECASE)

# Родительный требует не только предлог. В новостях сплошь и рядом
# "президент Турции", "столица Казахстана", "министр образования Узбекистана" —
# управляет существительное. Список закрытый и короткий: берём только то, что
# реально встречается в заголовках, иначе легко испортить нормальную фразу.
GENITIVE_HEADS = frozenset("""
президент премьер премьер-министр министр глава руководитель мэр аким хоким
губернатор посол посольство консульство правительство парламент президента
столица город область регион провинция район территория население жители
власти лидер председатель спикер делегация представитель представители
ministry университет академия институт центр агентство комитет совет
экономика экономики история культура народ народы граждане гражданин
визит поездка встреча переговоры заявление выступление слова речь интервью
решение указ приказ распоряжение инициатива предложение позиция мнение
отставка назначение приезд прибытие открытие закрытие итоги результаты
делегации сторонник противник житель жителей власть власти политика
""".split())


def _match_case(word, orig):
    """pymorphy отдаёт нижний регистр — возвращаем регистр оригинала."""
    if not word:
        return orig
    if orig.isupper():
        return word.upper()
    if orig[:1].isupper():
        return word[:1].upper() + word[1:]
    return word


# Имена собственные — главный источник промахов. "Токаев" pymorphy без
# подсказки разбирает как множественное число от "Токай" и в творительном
# выдаёт "Токаями". Поэтому среди разборов явно предпочитаем помеченные как
# фамилия/имя/топоним и единственное число.
_PROPER = ("Surn", "Name", "Patr", "Geox")


# Фамилии — слабое место словарной морфологии. "Эрдоган" в словаре pymorphy
# есть и склоняется верно, а "Токаев" и "Жапаров" — нет, и они разбираются как
# родительный падеж множественного числа несуществующих "токай" и "жапар":
# на выходе "Токаями", "Жапарами". Выбором разбора это не чинится — верного
# варианта среди них просто нет.
#
# Зато русские фамилии склоняются абсолютно регулярно, правилами. Их и
# применяем — но только когда словарь не дал приличного разбора, чтобы не
# ломать слова, которые он знает.
_SURN_NOUN = re.compile(r"(ов|ев|ёв|ин|ын|ян)$", re.IGNORECASE)
_SURN_ADJ = re.compile(r"(ский|цкий|ской|цкой)$", re.IGNORECASE)
# Несклоняемые: грузинские, азербайджанские, среднеазиатские типы.
_SURN_INDECL = re.compile(r"(швили|дзе|ури|оглу|огл|заде|уа|иа|ава)$", re.IGNORECASE)

_NOUN_ENDINGS = {"gent": "а", "datv": "у", "accs": "а", "ablt": "ым", "loct": "е"}
_ADJ_ENDINGS = {"gent": "ого", "datv": "ому", "accs": "ого", "ablt": "им", "loct": "ом"}


def _decline_surname(word, case):
    """Регулярное склонение мужской фамилии. None — если образец не подошёл."""
    if _SURN_INDECL.search(word):
        return word
    if _SURN_ADJ.search(word):
        end = _ADJ_ENDINGS.get(case)
        return word[:-2] + end if end else None
    if _SURN_NOUN.search(word):
        end = _NOUN_ENDINGS.get(case)
        return word + end if end else None
    return None


def _good_parse(p):
    """Разбор считаем годным, если он единственного числа: именно на этом
    сыплются неизвестные фамилии."""
    return p is not None and "sing" in p.tag


def _best_parse(m, word):
    parses = m.parse(word)
    if not parses:
        return None
    def rank(p):
        tags = p.tag
        score = 0
        if any(g in tags for g in _PROPER):
            score += 4
        if "sing" in tags:
            score += 2
        if "NOUN" in tags or "ADJF" in tags:
            score += 1
        return score
    return max(parses, key=rank)


def inflect_phrase(phrase, case):
    """Ставим фразу в падеж. Многословные термины ("Нагорный Карабах",
    "Самаркандская область") склоняем пословно: pymorphy согласует
    прилагательное с существительным, если обоим задать один падеж."""
    if not phrase or not case:
        return phrase
    try:
        m = _analyzer()
    except Exception:
        log.warning("morph: pymorphy3 недоступен, оставляю именительный")
        return phrase
    out, changed = [], False
    for tok in phrase.split(" "):
        core = _WORD.match(tok)
        if not core or not re.search(r"[А-Яа-яЁё]", tok):
            out.append(tok)
            continue
        w = core.group(0)
        tail = tok[len(w):]
        try:
            p = _best_parse(m, w)
            # -ян/-ов/-ев/-ин склоняем правилом всегда: словарные разборы для
            # них либо отсутствуют, либо адъективные ("Пашиняного").
            forced = _decline_surname(w, case) if _SURN_NOUN.search(w) else None
            if forced:
                out.append(_match_case(forced, w) + tok[len(w):])
                changed = True
                continue
            f = p.inflect({case}) if _good_parse(p) else None
            if f is None:
                byrule = _decline_surname(w, case)
                if byrule:
                    out.append(_match_case(byrule, w) + tok[len(w):])
                    changed = True
                    continue
        except Exception:
            f = None
        if f and f.word.lower() != w.lower():
            out.append(_match_case(f.word, w) + tail)
            changed = True
        else:
            out.append(tok)
    return " ".join(out) if changed else phrase


def case_before(text, pos):
    """Падеж, которого требует контекст слева от позиции pos. None — если
    управляющего предлога нет и надо оставить именительный."""
    left = text[:pos].rstrip()
    m = None
    for m in _WORD.finditer(left):
        pass
    if not m:
        return None
    # "Данные по Самаркандской области и Нагорному Карабаху": союз не управляет
    # ничем, падеж наследуется от той же группы. Заглядываем через него.
    if m.group(0).lower() in ("и", "или", "а", "либо"):
        # Между союзом и предлогом стоит первый однородный член, иногда из
        # нескольких слов: "по Самаркандской области и Нагорному Карабаху".
        # Отматываем до пяти слов назад в поисках управляющего.
        words = list(_WORD.finditer(left[:m.start()]))
        for wm in reversed(words[-5:]):
            lw = wm.group(0).lower()
            if lw in PREP_CASE or lw in GENITIVE_HEADS:
                return case_before(left, wm.end() + 1)
        return None
    # Предлог должен непосредственно примыкать: между ним и термином допустимы
    # только пробелы и кавычки, иначе управляет что-то другое.
    between = left[m.end():]
    if between.strip(" «\"'("):
        return None
    w = m.group(0).lower()
    if w in ("в", "во", "на") and _MOTION.search(left[-90:]):
        return "accs"          # движение: "прибыл в Бишкек", а не "в Бишкеке"
    if w in PREP_CASE:
        return PREP_CASE[w]
    if w in GENITIVE_HEADS:
        return "gent"
    return None
